"""
src/perception_fast_path_router.py — Perception Plane Fast-Path & SLM Authority Boundary

Implements Item 9 of the AEIB 12-item master delivery scope:
1. Edge SLMs (Tencent Hy-MT2 1.8B, Qwen-3.5-4B, Apple Neural Engine) are restricted
   strictly to the Perception and Proposal Plane (intent extraction, translation,
   candidate proposal synthesis).
2. Non-Authoritative Invariant: Edge SLMs never act as authorization oracles and
   cannot sign capability tokens or trigger direct wire mutations.
3. Fast-path local routing: read-only queries resolve sub-100 microseconds; mutations
   are strictly demoted to proposals and routed to the Station 1 Consequential Latch.
"""

import hashlib
import json
import time
from dataclasses import dataclass
from typing import Any, Callable, Dict, List, Optional, Set, Tuple

from src.jcs_canonicalizer import encode_jcs


class SlmAuthorityViolation(Exception):
    """Raised when an edge perception model attempts unauthorized execution."""
    pass


@dataclass(frozen=True)
class CandidateToolProposal:
    """Non-authoritative candidate proposal generated by an Edge SLM."""
    proposal_id: str
    slm_model_id: str
    target_tool: str
    proposed_arguments: Dict[str, Any]
    is_consequential: bool
    confidence_score: float
    generated_at: int


class PerceptionFastPathRouter:
    """
    Fast-path perception router integrating edge SLMs while strictly isolating action authority.
    """

    READ_ONLY_TOOLS = {
        "lookup_balance",
        "query_catalog",
        "get_order_status",
        "translate_text",
        "summarize_document",
        "check_inventory",
        "ping",
    }

    CONSEQUENTIAL_TOOLS = {
        "disburse_funds",
        "transfer_tokens",
        "delete_database_row",
        "update_kyc_record",
        "actuate_device_tap",
        "post_payment_intent",
    }

    def __init__(
        self,
        station1_dispatcher: Optional[Callable[[Dict[str, Any]], Dict[str, Any]]] = None,
        allowed_slm_models: Optional[Set[str]] = None,
    ) -> None:
        self.station1_dispatcher = station1_dispatcher or self._default_mock_station1
        self.allowed_slm_models = allowed_slm_models or {
            "tencent/hy-mt2-1.8b",
            "qwen/qwen-3.5-4b-instruct",
            "apple/ane-slm-core",
        }
        self.perception_cache: Dict[str, Tuple[Dict[str, Any], int]] = {}

    def _default_mock_station1(self, req: Dict[str, Any]) -> Dict[str, Any]:
        return {
            "status": "STATION1_ENQUEUED",
            "operation_id": req.get("operation_id", "op_gen"),
            "target_tool": req.get("target_tool"),
            "escrow_locked": True,
        }

    def evaluate_request(
        self,
        raw_prompt: str,
        slm_model_id: str,
        caller_claims_authority: bool = False,
    ) -> Dict[str, Any]:
        """
        Evaluates a user prompt using the Edge SLM perception plane.
        """
        if slm_model_id not in self.allowed_slm_models:
            raise SlmAuthorityViolation(f"HALT_UNREGISTERED_SLM_MODEL: {slm_model_id}")

        if caller_claims_authority:
            # An edge SLM can never claim direct execution authority!
            raise SlmAuthorityViolation(
                "HALT_SLM_AUTHORITY_ESCALATION: Perception plane models cannot authorize mutations"
            )

        # 1. Synthesize candidate proposal (deterministic classification scaffold)
        lower_prompt = raw_prompt.lower()
        is_consequential = any(
            kw in lower_prompt for kw in ["pay", "transfer", "disburse", "delete", "actuate", "execute"]
        )

        detected_tool = "translate_text" if "translate" in lower_prompt else (
            "transfer_tokens" if is_consequential else "lookup_balance"
        )

        prop_id = f"prop_{hashlib.sha256(raw_prompt.encode('utf-8')).hexdigest()[:16]}"
        proposal = CandidateToolProposal(
            proposal_id=prop_id,
            slm_model_id=slm_model_id,
            target_tool=detected_tool,
            proposed_arguments={"raw_query": raw_prompt, "synthetic_eval": True},
            is_consequential=is_consequential,
            confidence_score=0.94,
            generated_at=int(time.time()),
        )

        # 2. Fast-path routing vs Consequential Gate
        if not proposal.is_consequential:
            # Read-only path: resolves directly in Perception Plane without disk sync
            cache_key = hashlib.sha256(f"{slm_model_id}:{detected_tool}:{raw_prompt}".encode("utf-8")).hexdigest()
            cached = self.perception_cache.get(cache_key)
            if cached and (time.time() - cached[1] < 60):
                return {"routing": "PERCEPTION_CACHE_HIT", "result": cached[0]}

            result = {
                "routing": "PERCEPTION_FAST_PATH_RESOLVED",
                "tool": proposal.target_tool,
                "data": f"Informational perception result for: '{raw_prompt}'",
                "authority": "NON_AUTHORITATIVE_PROPOSAL",
            }
            self.perception_cache[cache_key] = (result, int(time.time()))
            return result

        # Consequential path: demote strictly to proposal and forward to Station 1
        station1_payload = {
            "operation_id": f"op_from_{proposal.proposal_id}",
            "source_proposal": proposal.proposal_id,
            "slm_model": proposal.slm_model_id,
            "target_tool": proposal.target_tool,
            "arguments": proposal.proposed_arguments,
            "status": "AWAITING_STATION1_WARRANT",
        }
        station1_resp = self.station1_dispatcher(station1_payload)
        return {
            "routing": "ROUTED_TO_STATION_1_CONSEQUENTIAL_LATCH",
            "proposal": {
                "id": proposal.proposal_id,
                "model": proposal.slm_model_id,
                "target_tool": proposal.target_tool,
                "is_consequential": True,
            },
            "station1_response": station1_resp,
        }
