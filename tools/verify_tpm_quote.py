"""
tools/verify_tpm_quote.py
================================================================================
Standalone TPM 2.0 / Confidential Computing Quote Verifier.
Evaluated under the stated model as an agent execution boundary scaffold.

Decouples quote verification from generation. Validates:
  1. Nonce freshness against caller-provided challenge (anti-replay).
  2. PCR register consistency and sorted composite hash recalculation.
  3. Attestation Key (AK) Ed25519 signature over canonical RFC 8785 JCS quote body.
  4. Operational trust mode: distinguishes between hardware-attested devices
     (physical / vTPM) and in-memory software simulation scaffolds.
  5. Optional certificate chain or trust anchor binding.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric import ed25519

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.jcs_canonicalizer import encode_jcs


class TpmQuoteVerificationError(Exception):
    """Raised when TPM quote verification fails closed."""
    pass


class StandaloneTpmQuoteVerifier:
    """
    Independent, zero-bypass verifier for TPM 2.0 PCR attestation quotes.
    Operates without dependency on the quote generator.
    """

    def __init__(self, trusted_ak_pubkey_b64: Optional[str] = None) -> None:
        self.trusted_ak_pubkey_b64 = trusted_ak_pubkey_b64
        self._trusted_ak_pubkey: Optional[ed25519.Ed25519PublicKey] = None
        if trusted_ak_pubkey_b64:
            raw_bytes = base64.b64decode(trusted_ak_pubkey_b64)
            self._trusted_ak_pubkey = ed25519.Ed25519PublicKey.from_public_bytes(raw_bytes)

    def verify_quote_dict(
        self,
        quote_data: Dict[str, Any],
        expected_nonce_hex: Optional[str] = None,
        expected_pcrs: Optional[Dict[int, str]] = None,
        enforce_hardware: bool = False,
    ) -> Dict[str, Any]:
        """
        Verifies a TPM quote dictionary.
        Returns a structured receipt if verification succeeds; raises TpmQuoteVerificationError if it fails.
        """
        # 1. Structural schema validation
        required_fields = [
            "ak_pubkey_b64",
            "clock_info",
            "composite_hash",
            "pcr_indices",
            "pcr_values",
            "qualifying_data_nonce",
            "signature_b64",
        ]
        for field_name in required_fields:
            if field_name not in quote_data:
                raise TpmQuoteVerificationError(f"HALT_TPM_QUOTE_MISSING_FIELD: {field_name}")

        is_hardware = bool(quote_data.get("is_hardware_tpm", False))
        if enforce_hardware and not is_hardware:
            raise TpmQuoteVerificationError(
                "HALT_TPM_HARDWARE_REQUIRED: Quote was generated by a software model scaffold, not hardware."
            )

        ak_pubkey_b64 = quote_data["ak_pubkey_b64"]
        if self.trusted_ak_pubkey_b64 and ak_pubkey_b64 != self.trusted_ak_pubkey_b64:
            raise TpmQuoteVerificationError("HALT_TPM_AK_PUBKEY_UNTRUSTED: Quote AK does not match trusted key.")

        # 2. Nonce freshness check
        quote_nonce = quote_data["qualifying_data_nonce"]
        if expected_nonce_hex is not None:
            if quote_nonce.lower() != expected_nonce_hex.lower():
                raise TpmQuoteVerificationError(
                    f"HALT_TPM_NONCE_MISMATCH: expected {expected_nonce_hex}, observed {quote_nonce}"
                )

        # 3. PCR index & value consistency
        pcr_indices = sorted([int(idx) for idx in quote_data["pcr_indices"]])
        pcr_values = {int(k): str(v).lower() for k, v in quote_data["pcr_values"].items()}

        for idx in pcr_indices:
            if idx not in pcr_values:
                raise TpmQuoteVerificationError(f"HALT_TPM_PCR_VALUE_MISSING: PCR {idx} in indices but not in values")
            val_hex = pcr_values[idx]
            if len(val_hex) != 64:
                raise TpmQuoteVerificationError(f"HALT_TPM_PCR_MALFORMED: PCR {idx} length is not 64 hex characters")

        # 4. Expected PCR values check
        if expected_pcrs:
            for exp_idx, exp_val in expected_pcrs.items():
                observed_val = pcr_values.get(exp_idx)
                if observed_val != exp_val.lower():
                    raise TpmQuoteVerificationError(
                        f"HALT_TPM_PCR_MISMATCH: PCR {exp_idx} expected {exp_val}, observed {observed_val}"
                    )

        # 5. Composite hash recalculation
        composite_hasher = hashlib.sha256()
        for idx in pcr_indices:
            composite_hasher.update(idx.to_bytes(4, "big"))
            composite_hasher.update(bytes.fromhex(pcr_values[idx]))
        computed_composite = composite_hasher.hexdigest()

        if computed_composite.lower() != str(quote_data["composite_hash"]).lower():
            raise TpmQuoteVerificationError(
                f"HALT_TPM_COMPOSITE_HASH_MISMATCH: computed {computed_composite}, quote claims {quote_data['composite_hash']}"
            )

        # 6. Reconstruct canonical quote body for RFC 8785 JCS verification
        canonical_quote_body = {
            "ak_pubkey_b64": ak_pubkey_b64,
            "clock_info": quote_data["clock_info"],
            "composite_hash": quote_data["composite_hash"],
            "is_hardware_tpm": is_hardware,
            "pcr_indices": pcr_indices,
            "pcr_values": {str(k): pcr_values[k] for k in pcr_indices},
            "qualifying_data_nonce": quote_nonce,
        }

        canonical_bytes = encode_jcs(canonical_quote_body)

        # 7. Signature verification
        raw_ak_pubkey = base64.b64decode(ak_pubkey_b64)
        ak_verifier = self._trusted_ak_pubkey or ed25519.Ed25519PublicKey.from_public_bytes(raw_ak_pubkey)

        sig_bytes = base64.b64decode(quote_data["signature_b64"])
        try:
            ak_verifier.verify(sig_bytes, canonical_bytes)
        except InvalidSignature:
            raise TpmQuoteVerificationError("HALT_TPM_SIGNATURE_INVALID: Ed25519 signature verification failed.")
        except Exception as exc:
            raise TpmQuoteVerificationError(f"HALT_TPM_VERIFICATION_EXCEPTION: {str(exc)}")

        # 8. Build verification receipt
        receipt = {
            "verdict": "VERIFIED",
            "is_hardware_tpm": is_hardware,
            "operational_mode": "HARDWARE_ATTESTED" if is_hardware else "SOFTWARE_MODEL_SCAFFOLD",
            "ak_pubkey_b64": ak_pubkey_b64,
            "qualifying_data_nonce": quote_nonce,
            "pcr_indices_evaluated": pcr_indices,
            "pcr_11_value": pcr_values.get(11),
            "composite_hash": computed_composite,
            "signature_verified": True,
            "recalculated_jcs_sha256": hashlib.sha256(canonical_bytes).hexdigest(),
            "evaluated_at_epoch_ms": int(time.time() * 1000),
        }
        return receipt


def self_test() -> None:
    """Executes full self-test of StandaloneTpmQuoteVerifier."""
    from src.tpm_pcr_attestation import TpmPcrAttestationEngine

    engine = TpmPcrAttestationEngine()
    # Bind an eBPF policy and SCITT root
    ebpf_map_digest = hashlib.sha256(b"ebpf_policy_map_standalone_test").hexdigest()
    scitt_root = hashlib.sha256(b"scitt_root_tree_size_500").hexdigest()
    extended_pcr11 = engine.bind_ebpf_policy_and_scitt_root(ebpf_map_digest, scitt_root)

    nonce = os.urandom(32)
    quote_record = engine.generate_quote(pcr_indices=[11], nonce=nonce)
    quote_dict = quote_record.to_canonical_dict()
    quote_dict["signature_b64"] = quote_record.signature_b64

    # 1. Positive verification
    verifier = StandaloneTpmQuoteVerifier()
    receipt = verifier.verify_quote_dict(
        quote_dict,
        expected_nonce_hex=nonce.hex(),
        expected_pcrs={11: extended_pcr11},
    )
    assert receipt["verdict"] == "VERIFIED"
    assert receipt["signature_verified"] is True
    assert receipt["pcr_11_value"] == extended_pcr11
    assert receipt["operational_mode"] == "SOFTWARE_MODEL_SCAFFOLD"

    # 2. Negative control: Tampered PCR 11
    tampered_quote = dict(quote_dict)
    tampered_quote["pcr_values"] = {"11": "0" * 64}
    try:
        verifier.verify_quote_dict(tampered_quote, expected_nonce_hex=nonce.hex())
        raise AssertionError("Expected failure on tampered PCR value")
    except TpmQuoteVerificationError as e:
        assert "HALT_TPM_COMPOSITE_HASH_MISMATCH" in str(e)

    # 3. Negative control: Replayed/mismatched nonce
    bad_nonce = os.urandom(32).hex()
    try:
        verifier.verify_quote_dict(quote_dict, expected_nonce_hex=bad_nonce)
        raise AssertionError("Expected failure on mismatched nonce")
    except TpmQuoteVerificationError as e:
        assert "HALT_TPM_NONCE_MISMATCH" in str(e)

    # 4. Negative control: Corrupted signature
    bad_sig_quote = dict(quote_dict)
    raw_sig = bytearray(base64.b64decode(bad_sig_quote["signature_b64"]))
    raw_sig[0] ^= 0xFF
    bad_sig_quote["signature_b64"] = base64.b64encode(raw_sig).decode("ascii")
    try:
        verifier.verify_quote_dict(bad_sig_quote, expected_nonce_hex=nonce.hex())
        raise AssertionError("Expected failure on corrupted signature")
    except TpmQuoteVerificationError as e:
        assert "HALT_TPM_SIGNATURE_INVALID" in str(e)

    # 5. Negative control: Hardware enforcement on software quote
    try:
        verifier.verify_quote_dict(quote_dict, expected_nonce_hex=nonce.hex(), enforce_hardware=True)
        raise AssertionError("Expected failure when enforcing hardware mode on software quote")
    except TpmQuoteVerificationError as e:
        assert "HALT_TPM_HARDWARE_REQUIRED" in str(e)

    print("[✓] StandaloneTpmQuoteVerifier: All self-test vectors passed cleanly.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Standalone TPM 2.0 / TDX Quote Verifier")
    parser.add_argument("--quote", help="Path to quote JSON file")
    parser.add_argument("--expected-nonce", help="Expected qualifying data nonce in hex")
    parser.add_argument("--expected-pcr11", help="Expected PCR 11 value in hex")
    parser.add_argument("--trusted-ak", help="Base64-encoded trusted Attestation Key public key")
    parser.add_argument("--enforce-hardware", action="store_true", help="Require genuine hardware TPM")
    parser.add_argument("--output-receipt", help="Path to write verification receipt JSON")
    parser.add_argument("--self-test", action="store_true", help="Run internal verification test suite")

    args = parser.parse_args()

    if args.self_test:
        self_test()
        sys.exit(0)

    if not args.quote:
        parser.print_help()
        sys.exit(1)

    quote_path = Path(args.quote)
    if not quote_path.exists():
        print(f"[!] Quote file not found: {quote_path}", file=sys.stderr)
        sys.exit(1)

    quote_data = json.loads(quote_path.read_text(encoding="utf-8"))
    expected_pcrs = {}
    if args.expected_pcr11:
        expected_pcrs[11] = args.expected_pcr11

    verifier = StandaloneTpmQuoteVerifier(trusted_ak_pubkey_b64=args.trusted_ak)
    try:
        receipt = verifier.verify_quote_dict(
            quote_data=quote_data,
            expected_nonce_hex=args.expected_nonce,
            expected_pcrs=expected_pcrs if expected_pcrs else None,
            enforce_hardware=args.enforce_hardware,
        )
        print(json.dumps(receipt, indent=2))
        if args.output_receipt:
            out_p = Path(args.output_receipt)
            out_p.parent.mkdir(parents=True, exist_ok=True)
            out_p.write_text(json.dumps(receipt, indent=2), encoding="utf-8")
            print(f"[✓] Receipt saved to: {out_p}")
        sys.exit(0)
    except TpmQuoteVerificationError as err:
        print(f"[!] TPM Quote Verification Failed: {err}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
